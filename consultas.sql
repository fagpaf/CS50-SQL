/* CONSULTA 50 - PROJETAR AS SIGLAS DOS EVENTOS COM ARTIGOS PUBLICADOS – USANDO “IN” */
SELECT E.SIGLA
FROM EVENTO E
WHERE  E. COD IN
               (SELECT A.COD  
                FROM ARTIGO A 
                WHERE A.COD IS NOT NULL);


/* CONSULTA 51 - PROJETAR OS TÍTULOS DOS ARTIGOS COM NOTA ABAIXO DA MÉDIA DOS ARTIGOS PUBLICADOS NO MESMO EVENTO*/
SELECT A1.TITULO
FROM ARTIGO A1
WHERE A1.NOTA <  
            ( SELECT AVG(NOTA)
	        FROM ARTIGO A2 
	        WHERE A1.COD = A2.COD);


/* CONSULTA 52 - PROJETAR AS SIGLAS DOS EVENTOS SEM ARTIGOS PUBLICADOS – USANDO “NOT EXISTS” */
SELECT E.SIGLA
FROM EVENTO E
WHERE  NOT EXISTS 
               (SELECT * 
                FROM ARTIGO A 
                WHERE A.COD = E.COD);


/* CONSULTA 53 - PROJETAR AS SIGLAS DOS EVENTOS SEM ARTIGOS PUBLICADOS – USANDO “NOT IN” */
SELECT E.SIGLA
FROM EVENTO E
WHERE E.COD  NOT IN
               (SELECT A.COD 
                FROM ARTIGO A 
                WHERE A.COD IS NOT NULL);


