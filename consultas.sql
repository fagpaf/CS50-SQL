/* CONSULTA 44 - PROJETAR OS TÍTULOS DOS ARTIGOS COM NOTA MAIOR DO QUE TODOS OS ARTIGOS DO EVENTO ‘SBBD21’ */
SELECT TITULO
FROM ARTIGO
WHERE NOTA >
    (SELECT MAX(NOTA)
    FROM ARTIGO A INNER JOIN EVENTO E ON (A.COD = E.COD)
    WHERE E.SIGLA = 'SBBD21');


/* CONSULTA 45 - PROJETAR OS TÍTULOS DOS ARTIGOS COM NOTA ACIMA DA MÉDIA GERAL, MOSTRANDO QUANTO A NOTA ESTÁ ACIMA DA MÉDIA */
SELECT TITULO, NOTA - (SELECT AVG(A.NOTA) FROM ARTIGO A)
FROM ARTIGO
WHERE NOTA >
    ( SELECT AVG(A.NOTA)
	FROM ARTIGO A);


/* CONSULTA 46 - PROJETAR O PERCENTUAL DE PESQUISADORES POR INSTITUIÇÃO */
SELECT INSTITUICAO, (QTD/(SELECT COUNT(*) FROM PESQUISADOR))*100 AS "%"
FROM 
	(SELECT INSTITUICAO, COUNT(*) AS QTD
	FROM PESQUISADOR
	GROUP BY INSTITUICAO);


/* CONSULTA 47 - PROJETAR QUAIS SÃO AS INSTITUIÇÕES QUE TÊM MAIS PESQUISADORES DO QUE A MÉDIA */
SELECT INSTITUICAO, COUNT(*)
FROM PESQUISADOR
GROUP BY INSTITUICAO
HAVING COUNT(*) > 
            ( SELECT AVG(QTD)
	        FROM (SELECT INSTITUICAO, COUNT (*) AS QTD 
	             FROM PESQUISADOR
	             GROUP BY INSTITUICAO));


